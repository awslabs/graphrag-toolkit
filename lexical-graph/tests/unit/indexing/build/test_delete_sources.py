def _label(cypher):
    return cypher.split('//', 1)[1].split('(delete source)')[0].strip()


def _ids(parameters):
    [value] = parameters.values()
    return [value] if isinstance(value, str) else list(value)


class _FakeGraph:
    """In-memory lexical graph that answers the DeleteSources queries by their leading comment.

    Chunks belong to a source. Topics and statements are mentioned in chunks, so they are
    found through the source's chunks, as the real queries find them. Statements support
    facts and facts reference entities. A fact survives while any statement still supports
    it, and an entity while any fact still references it.

    A query with LIMIT $batchSize returns at most that many rows. A node delete fails for
    any node whose relationships were not deleted first, as it would on a real graph.
    """

    def __init__(self):
        self.sources = set()
        self.chunks = {}
        self.topics = {}
        self.statements = {}
        self.facts = {}
        self.entities = set()
        self._detached = set()
        self._lock = threading.Lock()

    def add_chunk(self, chunk_id, source_id, topics=(), statements=None):
        self.sources.add(source_id)
        self.chunks[chunk_id] = source_id
        for topic_id in topics:
            self.topics.setdefault(topic_id, []).append(chunk_id)
        for statement_id, fact_ids in (statements or {}).items():
            chunk_ids, supported = self.statements.setdefault(statement_id, ([], []))
            chunk_ids.append(chunk_id)
            supported.extend(f for f in fact_ids if f not in supported)

    def add_fact(self, fact_id, *entity_ids):
        self.facts[fact_id] = list(entity_ids)
        self.entities.update(entity_ids)

    def _in_source(self, chunk_ids, source_id):
        return any(self.chunks.get(c) == source_id for c in chunk_ids)

    def execute_query(self, cypher, parameters):
        with self._lock:
            ids = self._read(_label(cypher), parameters)
        if 'LIMIT $batchSize' in cypher:
            ids = ids[:parameters['batchSize']]
        [key] = {
            'get chunk ids': ['chunkId'],
            'get topic ids': ['topicId'],
            'get statement ids': ['statementId'],
            'get fact ids': ['factId'],
            'get orphaned fact ids': ['factId'],
            'get entity ids': ['entityId'],
            'get orphaned entity ids': ['entityId'],
        }[_label(cypher)]
        return [{key: i} for i in ids]

    def _read(self, label, p):
        if label == 'get chunk ids':
            return [c for c, owner in self.chunks.items() if owner == p['sourceId']]
        if label == 'get topic ids':
            return [t for t, chunk_ids in self.topics.items() if self._in_source(chunk_ids, p['sourceId'])]
        if label == 'get statement ids':
            return [s for s, (chunk_ids, _) in self.statements.items() if self._in_source(chunk_ids, p['sourceId'])]
        if label == 'get fact ids':
            return list(dict.fromkeys(f for s in p['statementIds'] for f in self.statements.get(s, ([], []))[1]))
        if label == 'get entity ids':
            return list(dict.fromkeys(e for f in p['factIds'] for e in self.facts.get(f, [])))
        if label == 'get orphaned fact ids':
            supported = {f for _, fact_ids in self.statements.values() for f in fact_ids}
            return [f for f in dict.fromkeys(p['factIds']) if f in self.facts and f not in supported]
        if label == 'get orphaned entity ids':
            referenced = {e for entity_ids in self.facts.values() for e in entity_ids}
            return [e for e in dict.fromkeys(p['entityIds']) if e in self.entities and e not in referenced]
        raise AssertionError(f'unexpected query: {label}')

    def execute_query_with_retry(self, cypher, parameters):
        label = _label(cypher)
        ids = _ids(parameters)
        with self._lock:
            if label.endswith(' relationships'):
                self._detach(label, ids)
                self._detached.update(ids)
                return []
            attached = [i for i in ids if i not in self._detached]
            if attached:
                raise AssertionError(f'{label}: {attached} still have relationships')
            if label == 'delete statements':
                for s in ids:
                    self.statements.pop(s, None)
            elif label == 'delete facts':
                for f in ids:
                    self.facts.pop(f, None)
            elif label == 'delete entities':
                self.entities.difference_update(ids)
            elif label == 'delete topics':
                for t in ids:
                    self.topics.pop(t, None)
            elif label == 'delete chunks':
                for c in ids:
                    self.chunks.pop(c, None)
            elif label == 'delete source':
                self.sources.difference_update(ids)
            else:
                raise AssertionError(f'unexpected query: {label}')
        return []

    def _detach(self, label, ids):
        if label == 'delete statement relationships':
            for s in ids:
                if s in self.statements:
                    self.statements[s] = ([], [])
        elif label == 'delete fact relationships':
            for f in ids:
                if f in self.facts:
                    self.facts[f] = []
        elif label == 'delete topic relationships':
            for t in ids:
                if t in self.topics:
                    self.topics[t] = []
        elif label == 'delete chunk relationships':
            for c in ids:
                if c in self.chunks:
                    self.chunks[c] = None
            for chunk_ids, _ in self.statements.values():
                chunk_ids[:] = [c for c in chunk_ids if c not in ids]
            for chunk_ids in self.topics.values():
                chunk_ids[:] = [c for c in chunk_ids if c not in ids]
        elif label not in ('delete entity relationships', 'delete source relationships'):
            raise AssertionError(f'unexpected query: {label}')


def _vector_store():
    indexes = {name: MagicMock() for name in ('statement', 'topic', 'chunk')}
    store = MagicMock(spec=VectorStore)
    store.get_index.side_effect = lambda name: indexes[name]
    return store, indexes


def _deleted_embeddings(index):
    return [i for call in index.delete_embeddings.call_args_list for i in call.args[0]]


def _delete_sources(graph, vector_store, batch_size=10, num_workers=10):
    graph_store = MagicMock(spec=GraphStore)
    graph_store.node_id = lambda field: format_id(field)
    graph_store.execute_query.side_effect = graph.execute_query
    graph_store.execute_query_with_retry.side_effect = graph.execute_query_with_retry
    return DeleteSources.model_construct(
        graph_store=graph_store,
        vector_store=vector_store,
        num_workers=num_workers,
        batch_size=batch_size,
    )


class TestDeleteSourceDocument:

    def _graph(self):
        # Deleting with a batch size of 2 takes s1 and s2 first. Their facts are f-own,
        # which nothing else supports, and f-shared, which source-2's s9 still supports,
        # so one batch holds an orphaned fact and a surviving one. e-own and e-shared
        # split the same way. s3 and its fact f-solo make up the second batch.
        graph = _FakeGraph()
        graph.add_fact('f-own', 'e-own', 'e-shared')
        graph.add_fact('f-shared', 'e-shared', 'e-other')
        graph.add_fact('f-solo', 'e-solo')
        graph.add_chunk('c1', 'source-1', topics=['t1'], statements={'s1': ['f-own', 'f-shared']})
        graph.add_chunk('c2', 'source-1', topics=['t2'], statements={'s2': ['f-own']})
        graph.add_chunk('c3', 'source-1', topics=['t3'], statements={'s3': ['f-solo']})
        graph.add_chunk('c9', 'source-2', topics=['t9'], statements={'s9': ['f-shared']})
        return graph

    def _delete(self, graph, vector_store):
        return _delete_sources(graph, vector_store, batch_size=2).delete_source_document('source-1')

    def test_deletes_everything_the_source_owns(self):
        graph = self._graph()
        vector_store, _ = _vector_store()

        self._delete(graph, vector_store)

        assert graph.sources == {'source-2'}
        assert set(graph.chunks) == {'c9'}
        assert set(graph.topics) == {'t9'}
        assert set(graph.statements) == {'s9'}

    def test_keeps_facts_and_entities_another_source_still_uses(self):
        graph = self._graph()
        vector_store, _ = _vector_store()

        self._delete(graph, vector_store)

        assert set(graph.facts) == {'f-shared'}
        assert graph.entities == {'e-shared', 'e-other'}

    def test_removes_embeddings_from_each_index_in_batches(self):
        graph = self._graph()
        vector_store, indexes = _vector_store()

        self._delete(graph, vector_store)

        for name, ids in (('statement', ['s1', 's2', 's3']), ('topic', ['t1', 't2', 't3']), ('chunk', ['c1', 'c2', 'c3'])):
            assert sorted(_deleted_embeddings(indexes[name])) == ids
            assert indexes[name].delete_embeddings.call_count == 2

    def test_returns_the_counts_it_deleted(self):
        graph = self._graph()
        vector_store, _ = _vector_store()

        result = self._delete(graph, vector_store)

        assert result == {
            'sourceId': 'source-1',
            'chunks': 3,
            'topics': 3,
            'statements': 3,
            'facts': 2,
            'entities': 2,
        }

    def test_a_source_with_no_statements_still_deletes_its_chunks(self):
        graph = _FakeGraph()
        graph.add_chunk('c1', 'source-1')
        vector_store, indexes = _vector_store()

        result = _delete_sources(graph, vector_store).delete_source_document('source-1')

        assert graph.sources == set() and graph.chunks == {}
        assert result['chunks'] == 1 and result['statements'] == 0 and result['facts'] == 0
        indexes['statement'].delete_embeddings.assert_not_called()


class TestDeleteSourceDocuments:

    def test_deletes_every_source_and_returns_results_in_input_order(self):
        graph = _FakeGraph()
        for i in range(5):
            graph.add_chunk(f'c{i}', f'source-{i}', topics=[f't{i}'], statements={f's{i}': []})
        vector_store, _ = _vector_store()

        results = _delete_sources(graph, vector_store, num_workers=2).delete_source_documents(
            [f'source-{i}' for i in range(5)]
        )

        assert [r['sourceId'] for r in results] == [f'source-{i}' for i in range(5)]
        assert all(r['chunks'] == 1 and r['statements'] == 1 for r in results)
        assert graph.sources == set() and graph.statements == {}

    def test_no_source_ids_does_nothing(self):
        graph = _FakeGraph()
        vector_store, _ = _vector_store()

        assert _delete_sources(graph, vector_store).delete_source_documents([]) == []
