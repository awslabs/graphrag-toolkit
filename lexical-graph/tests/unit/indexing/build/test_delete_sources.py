"""
Tests for DeleteSources cascade deletion.

The query tests check that the Cypher generated by DeleteSources methods
contains the correct property names and relationship types, preventing
reintroduction of typos that caused incorrect orphan detection, missed cleanup,
and failed deletions. Each is run with both Neo4j-style and Neptune-style mock
graph stores.

The deletion tests run delete_source_document and delete_source_documents
against an in-memory graph and check what is left afterwards.
"""

